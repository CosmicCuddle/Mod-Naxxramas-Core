#!/usr/bin/env python3
"""Pinned Playerbots chat-ingress and eventual command execution boundary.

These source checks are documentation of *missing authoritative acceptance*,
not a runtime command collector. No game server or player is accessed.
"""
import argparse
from pathlib import Path


def read(root, filename):
    return (root / filename).read_text(encoding="utf-8")


def unique_section(source, first, last):
    assert source.count(first) == 1, "Pinned source changed: " + first
    section = source.split(first, 1)[1]
    assert last in section, "Pinned source end changed: " + last
    return section.split(last, 1)[0]


def check(bot_root):
    hooks = read(bot_root, "src/Script/Playerbots.cpp")
    ai = read(bot_root, "src/Bot/PlayerbotAI.cpp")
    helper = read(bot_root, "src/Bot/Engine/ExternalEventHelper.cpp")
    mgr = read(bot_root, "src/Bot/PlayerbotMgr.cpp")

    whisper = unique_section(
        hooks,
        "bool OnPlayerCanUseChat(Player* player, uint32 type, uint32 /*lang*/, std::string& msg, Player* receiver) override",
        "bool OnPlayerCanUseChat(Player* player, uint32 type, uint32 /*lang*/, std::string& msg, Group* group) override",
    )
    assert "if (type != CHAT_MSG_WHISPER)" in whisper
    assert "GetPlayerbotAI(receiver)" in whisper
    assert "botAI->HandleCommand(type, msg, player);" in whisper
    assert "return true;" in whisper

    group = unique_section(
        hooks,
        "bool OnPlayerCanUseChat(Player* player, uint32 type, uint32 /*lang*/, std::string& msg, Group* group) override",
        "bool OnPlayerCanUseChat(Player* player, uint32 type, uint32 /*lang*/, std::string& msg, Guild*",
    )
    assert "botAI->HandleCommand(type, msg, player);" in group

    command = unique_section(
        ai,
        "void PlayerbotAI::HandleCommand(uint32 type, std::string const& text, Player& fromPlayer, const uint32 lang)",
        "void PlayerbotAI::HandleTeleportAck()",
    )
    assert "CheckLevelFor(PlayerbotSecurityLevel::PLAYERBOT_SECURITY_INVITE" in command
    assert "CheckLevelFor(PlayerbotSecurityLevel::PLAYERBOT_SECURITY_ALLOW_ALL" in command
    assert "if (type == CHAT_MSG_ADDON)" in command
    assert "if (type == CHAT_MSG_SYSTEM)" in command
    assert "sPlayerbotAIConfig.commandPrefix" in command
    assert "chatFilter.Filter" in command
    assert "chatCommands.push_back(ChatCommandHolder(filtered, &fromPlayer, type));" in command

    # Notice the sender may be a real actor, but the actual command is
    # queued for later; a pre-chat event does not prove any action ran.
    assert command.index("CheckLevelFor(PlayerbotSecurityLevel::PLAYERBOT_SECURITY_INVITE") < (
        command.index("chatCommands.push_back(ChatCommandHolder(filtered, &fromPlayer, type));"))

    assert "Player* owner = it->GetOwner();" in ai
    assert "helper.ParseChatCommand(command, owner)" in ai
    assert "if (command.empty())" in ai
    assert "if (checkTime && time(nullptr) < checkTime)" in ai

    assert "bool ExternalEventHelper::ParseChatCommand(" in helper
    assert "Trigger* trigger = aiObjectContext->GetTrigger(name);" in helper
    assert "trigger->ExternalEvent(param, owner);" in helper

    assert "void PlayerbotMgr::HandleCommand(uint32 type, std::string const text)" in mgr
    assert "botAI->HandleCommand(type, text, master);" in mgr
    # A bot can also feed commands through AI code without a real received
    # packet. The sender pointer can be the bot for internal commands.
    assert "botAI->HandleCommand(CHAT_MSG_WHISPER, cmd.str(), bot);" in read(
        bot_root, "src/Ai/Base/Actions/CastCustomSpellAction.cpp"
    )

    print("PASS: chat ingress passes a sender to Playerbots before its security checks.")
    print("PASS: Playerbots may defer commands to its separate trigger/action queue.")
    print("PASS: internal commands can be generated by Playerbots, not a human client.")
    print("BLOCKED: Naxx chat observation proves neither AI acceptance nor applied pet ON/OFF.")
    print("Source audit only; no chat interception, pet toggle, SQL or server modification.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--playerbots", type=Path, required=True)
    args = parser.parse_args()
    check(args.playerbots.resolve())
